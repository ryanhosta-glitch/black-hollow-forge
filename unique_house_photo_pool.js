// Only these files are shipped. Keep the planned catalog above without selecting missing color assets.
export const AVAILABLE_HOUSE_PHOTOS=Object.freeze(HOUSE_PHOTO_LIBRARY.filter(photo=>photo.file.endsWith('_bw.webp')));


function makeSeededRng(seed = 1) {
  let state = (seed >>> 0) || 1;
  return () => {
    state = (1664525 * state + 1013904223) >>> 0;
    return state / 4294967296;
  };
}

function scorePhoto(photo, { roomType = '', preferredTags = [], requireStyle = '', orientation = '' } = {}) {
  let score = 0;
  if (roomType && photo.rooms.includes(roomType)) score += 6;
  if (requireStyle && photo.style === requireStyle) score += 8;
  if (orientation && photo.orientation === orientation) score += 2;
  for (const tag of preferredTags) if (photo.tags.includes(tag)) score += 3;
  return score;
}

/**
 * One-use-per-house allocator.
 * Each house should create ONE allocator instance, then call claim() for every photo slot.
 * A photo ID cannot repeat within that house instance.
 */
export function createUniqueHousePhotoAllocator({
  photos = AVAILABLE_HOUSE_PHOTOS,
  seed = 1,
  basePath = 'assets/portraits/'
} = {}) {
  const used = new Set();
  const canonical = photo => photo.artworkId || photo.id.replace(/_bw$/, "");
  const rng = makeSeededRng(seed);

  function normalizeCriteria(criteria = {}) {
    return {
      roomType: criteria.roomType || '',
      preferredTags: Array.isArray(criteria.preferredTags) ? criteria.preferredTags : [],
      requireStyle: criteria.requireStyle || 'victorian_bw',
      orientation: criteria.orientation || 'portrait'
    };
  }

  function withPath(photo) {
    return { ...photo, src: basePath + photo.file };
  }

  function pickBest(candidates, criteria) {
    const ranked = candidates
      .map(photo => ({ photo, score: scorePhoto(photo, criteria), roll: rng() }))
      .sort((a, b) => (b.score - a.score) || (a.roll - b.roll));
    return ranked.length ? ranked[0].photo : null;
  }

  return {
    get usedIds() {
      return [...used];
    },
    reset() {
      used.clear();
    },
    hasUnused() {
      return photos.some(photo => photo.style === "victorian_bw" && !used.has(canonical(photo)));
    },
    claim(criteria = {}) {
      const normalized = normalizeCriteria(criteria);
      const unused = photos.filter(photo => !used.has(canonical(photo)));
      if (!unused.length) return null;

      // Pass 1: fully filtered candidates.
      let candidates = unused.filter(photo => {
        if (normalized.requireStyle && photo.style !== normalized.requireStyle) return false;
        if (normalized.orientation && photo.orientation !== normalized.orientation) return false;
        if (normalized.roomType && !photo.rooms.includes(normalized.roomType)) return false;
        return true;
      });

      // Pass 2: relax room requirement but keep style/orientation.
      if (!candidates.length) {
        candidates = unused.filter(photo => {
          if (normalized.requireStyle && photo.style !== normalized.requireStyle) return false;
          if (normalized.orientation && photo.orientation !== normalized.orientation) return false;
          return true;
        });
      }

      // Never substitute color for black-and-white when style is explicitly requested.
      if (!candidates.length) return null;

      const picked = pickBest(candidates, normalized);
      if (!picked) return null;
      used.add(canonical(picked));
      return withPath(picked);
    }
  };
}

/**
 * Convenience helper for placing many photo slots in one house.
 * Each slot should look like:
 * { roomId:'r12', roomType:'gallery', preferredTags:['family'], requireStyle:'victorian_bw' }
 */
export function buildUniqueHousePhotoPlan(slots = [], options = {}) {
  const allocator = createUniqueHousePhotoAllocator(options);
  return slots.map(slot => ({
    ...slot,
    photo: allocator.claim(slot)
  }));
}
